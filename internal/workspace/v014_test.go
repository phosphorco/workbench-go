func strings2(values ...string) *[]string { return &values }
func boolean(value bool) *bool            { return &value }
func options(t *testing.T, source string) orderedjson.Value {
	t.Helper()
	value, err := orderedjson.Decode([]byte(source))
	if err != nil {
		t.Fatal(err)
	}
	return value
}

// layoutFixture is a small monorepo: a root base, a nested @p base, packages
// @p/core (sources, test overlapping src), @a/app (sources, test, tools) and
// a root tools project.
func layoutFixture(t *testing.T) LayoutInput {
	t.Helper()
	marker := "Generated by workbench"
	noEmit := options(t, `{"noEmit": true}`)
	core := LayoutPackage{
		Name: "@p/core", Directory: "pkg/@p/core",
		Policy: contract.PackagePolicy{Exports: map[string]string{".": "./src/index.ts", "./testing/*": "./testing/*.ts"}, Private: boolean(true)},
		Roles: []LayoutRole{
			{Name: "sources", Config: "pkg/@p/core/tsconfig.sources.json", Role: contract.Role{Include: strings2("./src"), CompilerOptions: options(t, `{"types": ["bun"], "lib": ["ES2024"]}`)},
				Files: []string{"pkg/@p/core/src/index.ts"}},
			{Name: "test", Config: "pkg/@p/core/tsconfig.test.json", Role: contract.Role{Include: strings2("./src", "./__tests__", "./testing"), AlsoIncludes: []string{"sources"}, Development: true, Consumes: []string{"sources"}, CompilerOptions: noEmit},
				Files: []string{"pkg/@p/core/__tests__/a.test.ts", "pkg/@p/core/src/index.ts", "pkg/@p/core/testing/fixture.ts"}},
		},
	}
	app := LayoutPackage{
		Name: "@a/app", Directory: "pkg/@a/app",
		Policy: contract.PackagePolicy{
			DevDependencies: map[string]string{"typescript": "catalog:"},
			Fields:          options(t, `{"version": "1.0.0", "sideEffects": false, "bin": {"app": "src/cli.ts"}}`),
		},
		Roles: []LayoutRole{
			{Name: "sources", Config: "pkg/@a/app/tsconfig.sources.json", Role: contract.Role{Include: strings2("./src")},
				Files: []string{"pkg/@a/app/src/cli.ts"}, Imports: []Import{{Specifier: "@p/core", Source: "pkg/@a/app/src/cli.ts"}, {Specifier: "@p/core/testing/fixture", Source: "pkg/@a/app/src/cli.ts"}, {Specifier: "fs", Source: "pkg/@a/app/src/cli.ts"}}},
			{Name: "test", Config: "pkg/@a/app/tsconfig.test.json", Role: contract.Role{Include: strings2("./__tests__"), Development: true, Consumes: []string{"sources"}, References: []string{"@p/core"}, CompilerOptions: noEmit},
				Files: []string{"pkg/@a/app/__tests__/cli.test.ts"}, Imports: []Import{{Specifier: "@p/core", Source: "pkg/@a/app/__tests__/cli.test.ts"}}},
			{Name: "tools", Config: "pkg/@a/app/tsconfig.tools.json", Role: contract.Role{Include: strings2("./vite.config.mts"), Development: true},
				Files: []string{"pkg/@a/app/vite.config.mts"}},
		},
	}
	return LayoutInput{
		Packages: []LayoutPackage{core, app},
		Projects: []LayoutRole{{Name: "tsconfig.tools.json", Config: "tsconfig.tools.json",
			Role:  contract.Role{Include: strings2("./tools/**/*.ts"), References: []string{"@p/core", "@a/app#tools"}, Development: true, CompilerOptions: noEmit},
			Files: []string{"tools/build.ts"}, Imports: []Import{{Specifier: "@a/app", Source: "tools/build.ts"}}}},
		Bases: map[string]contract.TsconfigBase{
			"root": {Directory: ".", CompilerOptions: options(t, `{"strict": true, "rootDir": "./"}`), Include: strings2("${configDir}/src"), Exclude: strings2("./**/fixtures")},
			"p":    {Directory: "pkg/@p", CompilerOptions: options(t, `{"target": "ES2022"}`)},
		},
		Root: &contract.RootManifest{PackageJSON: struct {
			Fields orderedjson.Value `json:"fields"`
		}{Fields: options(t, `{"name": "mono", "private": true, "workspaces": ["pkg/@*/*"], "catalog": {"typescript": "5.9.3"}, "devDependencies": {"typescript": "catalog:"}}`)}},
		GeneratedMarker:     &marker,
		RuntimeBuiltins:     map[string]bool{"fs": true},
		ManifestDirectories: []string{"pkg/@p/core", "pkg/@a/app"},
	}
}

func buildLayoutFixture(t *testing.T, mutate func(*LayoutInput)) (LayoutProjection, error) {
	t.Helper()
	input := layoutFixture(t)
	if mutate != nil {
		mutate(&input)
	}
	return BuildLayout(input)
}

func decodeFile(t *testing.T, projection LayoutProjection, name string) map[string]any {
	t.Helper()
	contents, exists := projection.Files[name]
	if !exists {
		t.Fatalf("%s was not projected; files: %v", name, sortedKeysOf(projection.Files))
	}
	var value map[string]any
	if err := json.Unmarshal(contents, &value); err != nil {
		t.Fatal(err)
	}
	return value
}

func TestBuildLayoutRendersRolesBasesIndexesAndRoot(t *testing.T) {
	projection, err := buildLayoutFixture(t, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		".tsconfigs/tsconfig.sources.child-index.json", ".tsconfigs/tsconfig.test.child-index.json", ".tsconfigs/tsconfig.tools.child-index.json",
		"package.json", "pkg/@a/app/package.json", "pkg/@a/app/tsconfig.json", "pkg/@a/app/tsconfig.sources.json", "pkg/@a/app/tsconfig.test.json", "pkg/@a/app/tsconfig.tools.json",
		"pkg/@p/.tsconfigs/tsconfig.sources.child-index.json", "pkg/@p/.tsconfigs/tsconfig.test.child-index.json", "pkg/@p/core/package.json", "pkg/@p/core/tsconfig.json",
		"pkg/@p/core/tsconfig.sources.json", "pkg/@p/core/tsconfig.test.json", "pkg/@p/tsconfig.base.json", "pkg/@p/tsconfig.json", "tsconfig.base.json", "tsconfig.json", "tsconfig.tools.json",
	}
	if got := sortedKeysOf(projection.Files); strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("projected files:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	// Key order and declared compilerOptions order are part of the bytes.
	if got := string(projection.Files["pkg/@p/core/tsconfig.sources.json"]); got != `{
  "//": "Generated by workbench",
  "extends": "../tsconfig.base.json",
  "compilerOptions": {
    "types": [
      "bun"
    ],
    "lib": [
      "ES2024"
    ]
  },
  "include": [
    "./src"
  ],
  "references": []
}
` {
		t.Fatalf("core sources tsconfig:\n%s", got)
	}
	// The app's sources reference core's sources twice over (entry and a
	// testing/ export in core's noEmit test role, which falls back).
	app := decodeFile(t, projection, "pkg/@a/app/tsconfig.sources.json")
	if refs, _ := json.Marshal(app["references"]); string(refs) != `[{"path":"../../@p/core/tsconfig.sources.json"}]` {
		t.Fatalf("app sources references = %s", refs)
	}
	if len(projection.Notes) == 0 || projection.Notes[0].Kind != "referenceFallback" {
		t.Fatalf("notes = %#v", projection.Notes)
	}
	// Authored references and consumes.
	test := decodeFile(t, projection, "pkg/@a/app/tsconfig.test.json")
	if refs, _ := json.Marshal(test["references"]); string(refs) != `[{"path":"../../@p/core/tsconfig.sources.json"},{"path":"./tsconfig.sources.json"}]` {
		t.Fatalf("app test references = %s", refs)
	}
	tools := decodeFile(t, projection, "tsconfig.tools.json")
	if refs, _ := json.Marshal(tools["references"]); string(refs) != `[{"path":"./pkg/@a/app/tsconfig.tools.json"},{"path":"./pkg/@p/core/tsconfig.sources.json"}]` {
		t.Fatalf("root tools references = %s", refs)
	}
	// outDir is derived for the emitting tools role; noEmit roles get none.
	appTools := decodeFile(t, projection, "pkg/@a/app/tsconfig.tools.json")
	if outDir := appTools["compilerOptions"].(map[string]any)["outDir"]; outDir != "${configDir}/dist-types/tools" {
		t.Fatalf("tools outDir = %v", outDir)
	}
	if _, exists := test["compilerOptions"].(map[string]any)["outDir"]; exists {
		t.Fatal("a noEmit role received an outDir")
	}
	// Root bases carry composite and outDir; rootDir stays authored.
	base := decodeFile(t, projection, "tsconfig.base.json")
	compiler := base["compilerOptions"].(map[string]any)
	if compiler["composite"] != true || compiler["outDir"] != "${configDir}/dist-types" || compiler["rootDir"] != "./" {
		t.Fatalf("root base compilerOptions = %#v", compiler)
	}
	// package.json: no invented exports, private omitted when null, version
	// first and passthrough fields in declared order, derived dependencies.
	if got := string(projection.Files["pkg/@a/app/package.json"]); got != `{
  "//": "Generated by workbench",
  "name": "@a/app",
  "version": "1.0.0",
  "type": "module",
  "sideEffects": false,
  "bin": {
    "app": "src/cli.ts"
  },
  "dependencies": {
    "@p/core": "workspace:*"
  },
  "devDependencies": {
    "typescript": "catalog:"
  }
}
` {
		t.Fatalf("app package.json:\n%s", got)
	}
	// Indexes list every package beneath their directory.
	index := decodeFile(t, projection, "pkg/@p/.tsconfigs/tsconfig.test.child-index.json")
	if refs, _ := json.Marshal(index["references"]); string(refs) != `[{"path":"../core/tsconfig.test.json"}]` {
		t.Fatalf("@p test index = %s", refs)
	}
	solution := decodeFile(t, projection, "tsconfig.json")
	if refs, _ := json.Marshal(solution["references"]); string(refs) != `[{"path":"./.tsconfigs/tsconfig.sources.child-index.json"},{"path":"./.tsconfigs/tsconfig.test.child-index.json"},{"path":"./.tsconfigs/tsconfig.tools.child-index.json"},{"path":"./tsconfig.tools.json"}]` {
		t.Fatalf("root solution = %s", refs)
	}
	root := decodeFile(t, projection, "package.json")
	if root["workspaces"].([]any)[0] != "pkg/@*/*" {
		t.Fatalf("root workspaces = %#v", root["workspaces"])
	}
	if dependencies := root["devDependencies"].(map[string]any); dependencies["@a/app"] != "workspace:*" || dependencies["typescript"] != "catalog:" {
		t.Fatalf("root derived dependencies = %#v", dependencies)
	}
}

// TestRootDirLayoutIsPinned pins the emit layout the Dagger declaration
// handoff consumes: rootDir is an authored base option, so a root-base
// package emits dist-types/<package path>/src/... below its own directory,
// and Workbench never writes or moves it.
func TestRootDirLayoutIsPinned(t *testing.T) {
	projection, err := buildLayoutFixture(t, nil)
	if err != nil {
		t.Fatal(err)
	}
	base := decodeFile(t, projection, "tsconfig.base.json")["compilerOptions"].(map[string]any)
	app := decodeFile(t, projection, "pkg/@a/app/tsconfig.sources.json")
	if base["rootDir"] != "./" || base["outDir"] != "${configDir}/dist-types" || app["extends"] != "../../../tsconfig.base.json" {
		t.Fatalf("emit layout changed: base %#v, app extends %v", base, app["extends"])
	}
	if options, exists := app["compilerOptions"]; exists {
		if _, rootDir := options.(map[string]any)["rootDir"]; rootDir {
			t.Fatal("a role carries rootDir")
		}
	}
}

func TestBuildLayoutRefusals(t *testing.T) {
	for name, test := range map[string]struct {
		mutate func(*LayoutInput)
		want   string
	}{
		"undeclared overlap": {func(input *LayoutInput) { input.Packages[0].Roles[1].Role.AlsoIncludes = nil }, "declare the overlap with alsoIncludes"},
		"file outside the package": {func(input *LayoutInput) {
			input.Packages[0].Roles[0].Files = append(input.Packages[0].Roles[0].Files, "pkg/@a/app/src/cli.ts")
		}, "outside the package; declare it in foreignFiles"},
		"authored reference to a missing role":      {func(input *LayoutInput) { input.Projects[0].Role.References = []string{"@p/core#tools"} }, "declares no tools role"},
		"authored reference to a noEmit role":       {func(input *LayoutInput) { input.Projects[0].Role.References = []string{"@p/core#test"} }, "does not emit"},
		"authored reference to an unplaced package": {func(input *LayoutInput) { input.Projects[0].Role.References = []string{"@x/none"} }, "not a placed package"},
		"cross-package reference to a noEmit role through referenceRole": {func(input *LayoutInput) {
			input.Packages[1].Roles[1].Role.ReferenceRole = "test"
		}, "does not emit"},
		"multi-class other than peer and dev": {func(input *LayoutInput) {
			input.Packages[1].Policy.Dependencies = map[string]string{"typescript": "catalog:"}
		}, "only peerDependencies with devDependencies"},
		"missing catalog key": {func(input *LayoutInput) {
			input.Packages[1].Policy.DevDependencies = map[string]string{"typescript": "catalog:", "zod": "catalog:schemas"}
		}, `no catalogs.schemas["zod"]`},
		"workspaces glob that misses a package": {func(input *LayoutInput) {
			input.Root.PackageJSON.Fields = options(t, `{"name": "mono", "workspaces": ["pkg/@p/*"], "catalog": {"typescript": "1"}, "devDependencies": {"typescript": "1.0.0"}}`)
		}, "placed but not matched"},
		"workspaces glob matching an unplaced manifest": {func(input *LayoutInput) {
			input.ManifestDirectories = append(input.ManifestDirectories, "pkg/@z/stray")
		}, "matched but not placed"},
		"authored root workspace entry naming no package": {func(input *LayoutInput) {
			input.Root.PackageJSON.Fields = options(t, `{"name": "mono", "devDependencies": {"typescript": "1.0.0", "@x/none": "workspace:*"}}`)
		}, "is not a placed package"},
		"root without a compiler": {func(input *LayoutInput) {
			input.Root.PackageJSON.Fields = options(t, `{"name": "mono"}`)
			input.Packages[1].Policy.DevDependencies = nil
		}, "declares no typescript dependency"},
		"missing patched dependency": {func(input *LayoutInput) {
			input.Root.PackageJSON.Fields = options(t, `{"name": "mono", "devDependencies": {"typescript": "1.0.0"}, "patchedDependencies": {"x@1": "patches/x.patch"}}`)
			input.Packages[1].Policy.DevDependencies = nil
			input.Exists = func(string) bool { return false }
		}, "does not exist"},
		"non-exported import from a standalone project": {func(input *LayoutInput) {
			input.Projects[0].Imports = append(input.Projects[0].Imports, Import{Specifier: "@a/app/hidden", Source: "tools/build.ts"})
		}, `declare exports["./hidden"]`},
		"base in a package directory": {func(input *LayoutInput) {
			input.Bases["core"] = contract.TsconfigBase{Directory: "pkg/@p/core", CompilerOptions: options(t, `{}`)}
		}, "cannot be a package directory"},
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := buildLayoutFixture(t, test.mutate); err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("error = %v, want %q", err, test.want)
			}
		})
	}
}

func TestBuildLayoutAdmitsPeerAndDevForOneDependency(t *testing.T) {
	projection, err := buildLayoutFixture(t, func(input *LayoutInput) {
		input.Packages[1].Policy.PeerDependencies = map[string]string{"typescript": "catalog:"}
	})
	if err != nil {
		t.Fatal(err)
	}
	manifest := decodeFile(t, projection, "pkg/@a/app/package.json")
	if manifest["peerDependencies"].(map[string]any)["typescript"] != "catalog:" || manifest["devDependencies"].(map[string]any)["typescript"] != "catalog:" {
		t.Fatalf("peer+dev = %#v", manifest)
	}
}

// cyclicFixture makes @p/core's sources import @a/app, closing a cycle with
// the app's sources import of core.
func cyclicFixture(input *LayoutInput) {
	input.Packages[1].Policy.Exports = map[string]string{".": "./src/cli.ts"}
	input.Packages[0].Roles[0].Imports = []Import{{Specifier: "@a/app", Source: "pkg/@p/core/src/index.ts"}}
}

func TestCircularEdgeSetValidation(t *testing.T) {
	for name, test := range map[string]struct {
		edges []string
		want  string
	}{
		"an unmarked cycle":                 {nil, "has a cycle no circular edge closes"},
		"a mark that is not a derived edge": {[]string{"@p/core -> @a/app", "@a/app -> @x/none"}, "is not a derived sources reference"},
		"a mark outside every cycle":        {[]string{"@p/core -> @a/app", "@a/app -> @p/core"}, ""},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := buildLayoutFixture(t, func(input *LayoutInput) {
				cyclicFixture(input)
				input.CircularEdges = test.edges
				input.CircularSource = ".workbench/circular-edges.json"
			})
			if test.want == "" {
				if err != nil {
					t.Fatalf("both marks of a two-cycle: %v", err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), test.want) || !strings.Contains(err.Error(), ".workbench/circular-edges.json") {
				t.Fatalf("error = %v, want %q naming the generated file", err, test.want)
			}
		})
	}
	projection, err := buildLayoutFixture(t, func(input *LayoutInput) {
		cyclicFixture(input)
		input.CircularEdges = []string{"@p/core -> @a/app"}
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(projection.Files["pkg/@p/core/tsconfig.sources.json"]), `"path": "../../@a/app/tsconfig.sources.json",
      "circular": true`) {
		refs := projection.Files["pkg/@p/core/tsconfig.sources.json"]
		t.Fatalf("marked reference = %s", refs)
	}
	if projection.Graph.SourcesUnits != 1 || len(projection.Graph.SourcesCycleSizes) != 1 || projection.Graph.SourcesCycleSizes[0] != 2 {
		t.Fatalf("graph = %#v", projection.Graph)
	}
	// A mark outside the cycle: the edge exists but closes nothing.
	_, err = buildLayoutFixture(t, func(input *LayoutInput) {
		input.CircularEdges = []string{"@a/app -> @p/core"}
	})
	if err == nil || !strings.Contains(err.Error(), "closes no cycle") {
		t.Fatalf("mark outside every SCC = %v", err)
	}
	// A cycle inside one package through consumes.
	_, err = buildLayoutFixture(t, func(input *LayoutInput) {
		input.Packages[0].Roles[0].Role.Consumes = []string{"test"}
	})
	if err == nil || !strings.Contains(err.Error(), "cycle") {
		t.Fatalf("cycle inside one package = %v", err)
	}
}
