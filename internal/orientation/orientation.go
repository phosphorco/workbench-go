// Package orientation renders agent guidance from explicit Workbench facts.
package orientation

import (
	"fmt"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/phosphorco/workbench-go/internal/contract"
)

// Render projects explicit AgentInstructions into complete AGENTS.md bytes.
// It is pure: callers retain all filesystem authority and decide whether and
// where to persist the result.
func Render(instructions contract.AgentInstructions) ([]byte, error) {
	if err := instructions.Validate(); err != nil {
		return nil, fmt.Errorf("render agent orientation: %w", err)
	}

	entrypoints := slices.Clone(instructions.Subject.Entrypoints)
	sort.Strings(entrypoints)
	resources := slices.Clone(instructions.Resources)
	sort.Slice(resources, func(left, right int) bool {
		leftKey := resourceSortKey(resources[left])
		rightKey := resourceSortKey(resources[right])
		return leftKey < rightKey
	})
	generatedPaths := sortedUnique(instructions.GeneratedPaths)
	handOwnedPaths := sortedUnique(instructions.HandOwnedPaths)

	var output strings.Builder
	output.WriteString(strings.TrimRight(instructions.Prose, "\r\n"))
	output.WriteString("\n\n<!-- Generated by Workbench from explicit AgentInstructions facts. -->\n")
	output.WriteString("# Workbench orientation\n\n")
	output.WriteString("This file is generated and ignored. Change tracked context prose in ")
	output.WriteString("`AGENTS.pkl`; change desired state in the Subject or repository declarations.\n\n")

	output.WriteString("## Current work line\n\n")
	writeFact(&output, "Branch", instructions.Subject.WorkLine.Branch)
	writeFact(&output, "Base branch", instructions.Subject.WorkLine.BaseBranch)

	output.WriteString("\n### Entrypoints\n\n")
	writeStringList(&output, entrypoints)

	output.WriteString("\n## Participating repositories\n\n")
	if len(resources) == 0 {
		output.WriteString("- None.\n")
	} else {
		for _, resource := range resources {
			fmt.Fprintf(
				&output,
				"- %s - shape %s; GitHub %s; path %s; branch %s; health %s\n",
				quote(resource.Identity),
				quote(string(resource.Shape.Kind)),
				quote(resource.GitHub),
				quote(resource.CanonicalPath),
				quote(resource.Branch),
				quote(resource.Health),
			)
		}
	}

	output.WriteString("\n## Workbench commands\n\n")
	output.WriteString("- Reconcile this Workbench: `workbench setup`\n")
	output.WriteString("- Deliver an exact Change Set: `workbench commit`\n")
	output.WriteString("- Record a Workbench Snapshot: `workbench snapshot`\n")
	output.WriteString("- Retire a proven-recoverable orphan: `workbench prune`\n")

	output.WriteString("\n## Ownership warnings\n\n")
	output.WriteString("- `AGENTS.md` is generated and ignored; do not hand edit it.\n")
	output.WriteString("- `AGENTS.pkl` is Git-owned and is never rewritten by Workbench.\n")
	output.WriteString("- Workbench owns these generated paths completely:\n")
	writeIndentedStringList(&output, generatedPaths)
	output.WriteString("- Git owns these hand-owned paths; Workbench must preserve them:\n")
	writeIndentedStringList(&output, handOwnedPaths)

	return []byte(output.String()), nil
}

func resourceSortKey(resource contract.AgentResource) string {
	return strings.Join([]string{
		resource.Identity,
		resource.GitHub,
		resource.CanonicalPath,
		resource.Branch,
		resource.Health,
	}, "\x00")
}

func sortedUnique(values []string) []string {
	result := slices.Clone(values)
	sort.Strings(result)
	return slices.Compact(result)
}

func writeFact(output *strings.Builder, name, value string) {
	fmt.Fprintf(output, "- %s: %s\n", name, quote(value))
}

func writeStringList(output *strings.Builder, values []string) {
	if len(values) == 0 {
		output.WriteString("- None.\n")
		return
	}
	for _, value := range values {
		fmt.Fprintf(output, "- %s\n", quote(value))
	}
}

func writeIndentedStringList(output *strings.Builder, values []string) {
	if len(values) == 0 {
		output.WriteString("  - None.\n")
		return
	}
	for _, value := range values {
		fmt.Fprintf(output, "  - %s\n", quote(value))
	}
}

func quote(value string) string {
	return strconv.Quote(value)
}
