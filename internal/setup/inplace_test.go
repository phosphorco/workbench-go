func inPlaceGit(t *testing.T, directory string, arguments ...string) string {
	t.Helper()
	command := exec.Command("git", arguments...)
	command.Dir = directory
	command.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v: %s", arguments, err, output)
	}
	return string(output)
}

// inPlaceRepository creates a committed checkout whose origin names
// phosphorco/mono and returns its root.
func inPlaceRepository(t *testing.T, declaration string) string {
	t.Helper()
	root := t.TempDir()
	write(t, filepath.Join(root, "workbench-subject.pkl"), "amends \"workbench-contract:/0.14.0/InPlaceSubject.pkl\"\n\nentrypoint = \"https://github.com/phosphorco/mono\"\n")
	write(t, filepath.Join(root, "workbench.pkl"), declaration)
	write(t, filepath.Join(root, ".gitignore"), "ignored/\n")
	write(t, filepath.Join(root, "pkg/@a/core/src/index.ts"), "export const core = 1\n")
	write(t, filepath.Join(root, "pkg/@a/core/__tests__/core.test.ts"), "import { core } from \"../src/index.ts\"\nexport const t = core\n")
	write(t, filepath.Join(root, "pkg/@a/app/src/main.ts"), "import type { core } from \"@a/core\"\nexport type T = typeof core\n")
	inPlaceGit(t, root, "init", "-q", "-b", "main")
	inPlaceGit(t, root, "remote", "add", "origin", "git@github.com:phosphorco/mono.git")
	inPlaceGit(t, root, "add", "-A")
	inPlaceGit(t, root, "commit", "-q", "-m", "init")
	return root
}

func inPlaceToolchain(t *testing.T) Toolchain {
	t.Helper()
	return NewToolchain(requireEvaluator(t), requireBun(t))
}

func TestInPlaceSetupWritesOwnedFilesAndCheckIsAFixedPoint(t *testing.T) {
	root := inPlaceRepository(t, inPlaceDeclaration)
	toolchain := inPlaceToolchain(t)
	ctx := context.Background()
	report, err := CheckInPlace(ctx, root, toolchain)
	if err != nil {
		t.Fatal(err)
	}
	if report.Equal() || len(report.Missing) == 0 {
		t.Fatalf("a fresh checkout reported equal: %#v", report)
	}
	if status := inPlaceGit(t, root, "status", "--porcelain"); status != "" {
		t.Fatalf("--check wrote files:\n%s", status)
	}
	if !hasNote(report, "staleInclude", "./missing") {
		t.Fatalf("stale include not reported: %#v", report.Notes)
	}
	result, err := runInPlace(ctx, root, toolchain)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.ChangedPaths) != len(report.Missing) {
		t.Fatalf("changed %v, want %v", result.ChangedPaths, report.Missing)
	}
	// A type-only import of a workspace package creates the edge.
	app, err := os.ReadFile(filepath.Join(root, "pkg/@a/app/package.json"))
	if err != nil || !strings.Contains(string(app), `"@a/core": "workspace:*"`) {
		t.Fatalf("type-only import did not create a dependency: %s %v", app, err)
	}
	inPlaceGit(t, root, "add", "-A")
	inPlaceGit(t, root, "commit", "-q", "-m", "owned files")
	first, err := CheckInPlace(ctx, root, toolchain)
	if err != nil {
		t.Fatal(err)
	}
	second, err := CheckInPlace(ctx, root, toolchain)
	if err != nil {
		t.Fatal(err)
	}
	if !first.Equal() || !reflect.DeepEqual(first, second) {
		t.Fatalf("--check on a clean tree is not a deterministic fixed point:\n%#v\n%#v", first, second)
	}
	encoded, _ := json.Marshal(first)
	encodedAgain, _ := json.Marshal(second)
	if string(encoded) != string(encodedAgain) {
		t.Fatal("--check --json output is not deterministic")
	}
}

func hasNote(report CheckReport, kind, detail string) bool {
	for _, note := range report.Notes {
		if note.Kind == kind && strings.Contains(note.Detail, detail) {
			return true
		}
	}
	return false
}

func TestInPlaceObservationReadsUntrackedButNotIgnoredSources(t *testing.T) {
	root := inPlaceRepository(t, inPlaceDeclaration)
	toolchain := inPlaceToolchain(t)
	ctx := context.Background()
	if _, err := runInPlace(ctx, root, toolchain); err != nil {
		t.Fatal(err)
	}
	inPlaceGit(t, root, "add", "-A")
	inPlaceGit(t, root, "commit", "-q", "-m", "owned files")
	// An untracked, unignored source creates its edge before git add; an
	// ignored file is never an input.
	write(t, filepath.Join(root, "pkg/@a/core/src/uses-app.ts"), "import \"@a/app\"\n")
	report, err := CheckInPlace(ctx, root, toolchain)
	if err == nil {
		t.Fatalf("an untracked import of a package without exports passed the closure: %#v", report)
	}
	if !strings.Contains(err.Error(), "@a/app") {
		t.Fatalf("closure error = %v", err)
	}
	if err := os.Remove(filepath.Join(root, "pkg/@a/core/src/uses-app.ts")); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(root, "pkg/@a/core/src/ignored/x.ts"), "import \"@missing/ignored\"\n")
	write(t, filepath.Join(root, ".gitignore"), "ignored/\n")
	if report, err := CheckInPlace(ctx, root, toolchain); err != nil || !report.Equal() {
		t.Fatalf("an ignored file was observed: %#v %v", report, err)
	}
}

func TestInPlaceCheckReportsAndSetupDeletesExtraOwnedFiles(t *testing.T) {
	root := inPlaceRepository(t, inPlaceDeclaration)
	toolchain := inPlaceToolchain(t)
	ctx := context.Background()
	if _, err := runInPlace(ctx, root, toolchain); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(root, "pkg/@a/core/.tsconfigs/tsconfig.sources.child-index.json"), "{}\n")
	write(t, filepath.Join(root, "pkg/@a/core/tsconfig.stale.json"), "{}\n")
	write(t, filepath.Join(root, "pkg/@a/core/tsconfig.untracked.json"), "{}\n")
	inPlaceGit(t, root, "add", "pkg/@a/core/.tsconfigs", "pkg/@a/core/tsconfig.stale.json")
	inPlaceGit(t, root, "add", "-A", "pkg", "package.json", "tsconfig.json", "tsconfig.base.json", ".tsconfigs")
	inPlaceGit(t, root, "reset", "-q", "pkg/@a/core/tsconfig.untracked.json")
	report, err := CheckInPlace(ctx, root, toolchain)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"pkg/@a/core/.tsconfigs/tsconfig.sources.child-index.json", "pkg/@a/core/tsconfig.stale.json"}; !reflect.DeepEqual(report.Extra, want) {
		t.Fatalf("extra = %v, want %v (untracked files are never owned)", report.Extra, want)
	}
	if _, err := runInPlace(ctx, root, toolchain); err != nil {
		t.Fatal(err)
	}
	for _, removed := range report.Extra {
		if _, err := os.Stat(filepath.Join(root, removed)); !os.IsNotExist(err) {
			t.Fatalf("extra owned file %s survived setup: %v", removed, err)
		}
	}
	if _, err := os.Stat(filepath.Join(root, "pkg/@a/core/tsconfig.untracked.json")); err != nil {
		t.Fatalf("an untracked file was treated as owned: %v", err)
	}
}

func TestInPlaceRefusals(t *testing.T) {
	toolchain := inPlaceToolchain(t)
	ctx := context.Background()
	for name, test := range map[string]struct {
		declaration string
		prepare     func(t *testing.T, root string)
		want        string
	}{
		"origin names another repository": {inPlaceDeclaration, func(t *testing.T, root string) {
			inPlaceGit(t, root, "remote", "set-url", "origin", "https://github.com/phosphorco/other")
		}, "origin names phosphorco/other"},
		"a 0.13 declaration":            {strings.Replace(inPlaceDeclaration, "0.14.0", "0.13.0", 1), nil, "requires a 0.14.0 Repository declaration"},
		"a cross-repository include":    {inPlaceDeclaration + "includes { [\"phosphorco/other\"] {} }\n", nil, "refuses cross-repository includes"},
		"no authored root":              {strings.Replace(inPlaceDeclaration, "root = new RootManifest {", "local unused = new RootManifest {", 1), nil, "must declare root"},
		"a package without a directory": {strings.Replace(inPlaceDeclaration, "packages {\n", "packages {\n  [\"@a/loose\"] {}\n", 1), nil, "has no directory"},
		"a missing circular-edge file":  {inPlaceDeclaration + "circularEdges = new CircularEdgeSet { path = \".workbench/circular-edges.json\" }\n", nil, "remedy: generate it with the repository's own tooling"},
	} {
		t.Run(name, func(t *testing.T) {
			root := inPlaceRepository(t, test.declaration)
			if test.prepare != nil {
				test.prepare(t, root)
			}
			if _, err := CheckInPlace(ctx, root, toolchain); err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("error = %v, want %q", err, test.want)
			}
		})
	}
	// Not the top of the checkout.
	root := inPlaceRepository(t, inPlaceDeclaration)
	nested := filepath.Join(root, "pkg")
	write(t, filepath.Join(nested, "workbench-subject.pkl"), "amends \"workbench-contract:/0.14.0/InPlaceSubject.pkl\"\n\nentrypoint = \"https://github.com/phosphorco/mono\"\n")
	if _, err := CheckInPlace(ctx, nested, toolchain); err == nil || !strings.Contains(err.Error(), "top of its checkout") {
		t.Fatalf("nested root = %v", err)
	}
}

