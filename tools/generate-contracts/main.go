package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode/utf8"
)

type contract struct{ name, path string }

var contracts = []contract{
	{"localSubjectContract", "pkl/WorkbenchSubject.pkl"},
	{"localRepositoryContract", "pkl/PackageScopeRepository.pkl"},
	{"localRepositoryDeclarationContract", "pkl/Repository.pkl"},
	{"localAgentInstructionsContract", "pkl/AgentInstructions.pkl"},
	{"localWorkbenchCommitPlanContract", "pkl/WorkbenchCommitPlan.pkl"},
	{"localWorkbenchSnapshotContract", "pkl/WorkbenchSnapshot.pkl"},
	{"localVerifierContract", "pkl/Verifier.pkl"},
	{"localFocusContract", "pkl/Focus.pkl"},
}

const outputPath = "internal/setup/contracts_generated.go"

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("generate-contracts", flag.ContinueOnError)
	check := flags.Bool("check", false, "refuse when generated contracts are missing or stale")
	write := flags.Bool("write", false, "write generated contracts")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 || *check == *write {
		return errors.New("choose exactly one of --check or --write")
	}
	sources := make(map[string][]byte, len(contracts))
	for _, c := range contracts {
		contents, err := os.ReadFile(filepath.FromSlash(c.path))
		if err != nil {
			return fmt.Errorf("read %s: %w", c.path, err)
		}
		sources[c.name] = contents
	}
	generated, err := render(sources)
	if err != nil {
		return err
	}
	current, err := os.ReadFile(outputPath)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read %s: %w", outputPath, err)
	}
	if *check {
		if !bytes.Equal(current, generated) {
			return errors.New("embedded contracts are missing or stale; run go run ./tools/generate-contracts --write")
		}
		return nil
	}
	if bytes.Equal(current, generated) {
		return nil
	}
	return os.WriteFile(outputPath, generated, 0o644)
}

func render(sources map[string][]byte) ([]byte, error) {
	var output strings.Builder
	output.WriteString("// Code generated by go run ./tools/generate-contracts --write; DO NOT EDIT.\n\npackage setup\n")
	for _, c := range contracts {
		contents, exists := sources[c.name]
		if !exists {
			return nil, fmt.Errorf("missing source for %s", c.name)
		}
		if !utf8.Valid(contents) || bytes.ContainsAny(contents, "\x00\r") {
			return nil, fmt.Errorf("%s contains bytes unsafe for a Go raw string", c.path)
		}
		parts := strings.Split(string(contents), "`")
		for i := range parts {
			parts[i] = "`" + parts[i] + "`"
		}
		fmt.Fprintf(&output, "\nconst %s = %s\n", c.name, strings.Join(parts, " + "+strconv.Quote("`")+" + "))
	}
	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated contracts: %w", err)
	}
	return formatted, nil
}
